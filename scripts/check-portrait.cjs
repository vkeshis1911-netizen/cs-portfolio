const { chromium } = require('@playwright/test')
const assert = require('node:assert/strict')
const path = require('node:path')
const os = require('node:os')

;(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://localhost:3001', { waitUntil: 'domcontentloaded' })
  const coin = page.getByRole('group', { name: /Interactive portrait coin/ })
  assert.equal(await coin.locator('img').count(), 0, 'Loading must not flash the old portrait')
  await coin.locator('canvas').waitFor()
  await page.waitForFunction(() => document.querySelector('[data-coin-x]'))
  const state = () => coin.evaluate(el => ({ x: +el.dataset.coinX, y: +el.dataset.coinY, rotation: +el.dataset.coinRotation }))
  await page.waitForTimeout(1300)
  const first = await state()
  await page.waitForTimeout(1200)
  const second = await state()
  assert(Math.abs(first.rotation - second.rotation) > 0.1, 'Coin must flip during entrance')
  await page.screenshot({ path: path.join(os.tmpdir(), 'coin-desktop.png') })
  await page.waitForTimeout(24000)
  const resting = await state()
  console.log({ first, second, resting })
  assert(Math.abs(resting.x - 260) < 8, 'Coin must settle near the center')
  assert(Math.cos(resting.rotation) > 0.98, 'Coin must settle portrait-forward')
  assert(Math.abs(resting.rotation) <= Math.PI * 4 + 0.1, 'Entrance must finish within two turns')
  await page.screenshot({ path: path.join(os.tmpdir(), 'coin-resting.png') })
  const bounds = await coin.boundingBox()
  const x = bounds.x + resting.x / 520 * bounds.width
  const y = bounds.y + resting.y / 480 * bounds.height
  await page.mouse.move(x, y)
  await page.mouse.down()
  await page.mouse.move(x + 90, y - 65, { steps: 20 })
  await page.waitForTimeout(300)
  const dragged = await state()
  await page.mouse.up()
  await page.waitForTimeout(1500)
  const released = await state()
  console.log({ dragged, released })
  assert(Math.abs(dragged.x - resting.x) > 15, 'Dragging must move the coin')
  assert(Math.abs(released.x - dragged.x) > 10, 'Release must swing the coin')
  const screenshot = await coin.locator('canvas').screenshot()
  const { data, info } = await require('sharp')(screenshot).raw().toBuffer({ resolveWithObject: true })
  let pixels = 0
  for (let i = 0; i < data.length; i += info.channels) if (data[i] < 180) pixels++
  console.log({ pixels, errors })
  assert(pixels > 5000, 'Rendered coin must contain visible pixels')
  assert.equal(errors.length, 0)
  await page.setViewportSize({ width: 1440, height: 1800 })
  await page.evaluate(() => scrollTo(0, 0))
  await page.waitForTimeout(500)
  const current = await state()
  const area = await coin.boundingBox()
  const end = await page.locator('#group-projects').boundingBox()
  const scale = area.width / 520
  await page.mouse.move(area.x + current.x * scale, area.y + current.y * scale)
  await page.mouse.down()
  await page.mouse.move(area.x - 30, end.y - 160 * scale, { steps: 35 })
  await page.waitForTimeout(1200)
  const extended = await state()
  console.log({ extended, endY: end.y })
  assert(extended.x < 100, 'Coin must travel farther sideways')
  assert(area.y + extended.y * scale > end.y - 240 * scale, 'Coin must reach the end of the recent project section')
  await page.screenshot({ path: path.join(os.tmpdir(), 'coin-extended.png') })
  await page.mouse.up()
  await page.locator('a[href="#recent-project"]').last().click({ trial: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await coin.scrollIntoViewIfNeeded()
  await page.waitForTimeout(1200)
  await page.screenshot({ path: path.join(os.tmpdir(), 'coin-mobile.png') })
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile must not overflow')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.reload({ waitUntil: 'domcontentloaded' })
  await coin.scrollIntoViewIfNeeded()
  await page.waitForTimeout(1000)
  assert(Math.abs((await state()).rotation) < 0.01, 'Reduced motion must skip the intro')
  await browser.close()
})().then(() => process.exit(0)).catch(error => { console.error(error); process.exit(1) })
